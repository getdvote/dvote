type Shape<T> = T extends string
  ? string
  : T extends readonly string[]
    ? readonly string[]
    : T extends PluralForms
      ? PluralForms
      : { [K in keyof T]: Shape<T[K]> };

/** The shape every language must have. */
export type Dictionary = Shape<typeof en>;
